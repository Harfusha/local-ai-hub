def test_benchmark_input_fingerprint_uses_imported_source_root(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    benchmark = _load_benchmark_module()
    project_root = tmp_path / "project"
    script_path = project_root / "tools" / "benchmark_t10_repository.py"
    source_root = tmp_path / "alternate-source"
    script_path.parent.mkdir(parents=True)
    script_path.write_bytes(BENCHMARK_PATH.read_bytes())
    for relative, value in (
        ("code_index.py", b"imported index\n"),
        ("repo_tools.py", b"imported repo tools\n"),
        ("retrieval.py", b"imported retrieval ranker\n"),
        ("treesitter_parser.py", b"imported parser\n"),
    ):
        target = source_root / "local_ai_hub" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(value)
    pycache = source_root / "local_ai_hub" / "__pycache__"
    pycache.mkdir()
    (pycache / "generated.pyc").write_bytes(b"generated bytecode")

    monkeypatch.setattr(benchmark, "__file__", str(script_path))
    monkeypatch.setattr(benchmark, "SOURCE_ROOT", source_root)
    monkeypatch.delenv("T10_BENCH_SOURCE_REVISION", raising=False)
    monkeypatch.delenv("T10_BENCH_SOURCE_FINGERPRINT", raising=False)

    identity = benchmark._source_identity()
    framed = b"".join(
        relative.encode("utf-8") + b"\0" + path.read_bytes() + b"\0"
        for relative, path in (
            ("tools/benchmark_t10_repository.py", script_path),
            ("src/local_ai_hub/code_index.py", source_root / "local_ai_hub" / "code_index.py"),
            ("src/local_ai_hub/repo_tools.py", source_root / "local_ai_hub" / "repo_tools.py"),
            ("src/local_ai_hub/retrieval.py", source_root / "local_ai_hub" / "retrieval.py"),
            ("src/local_ai_hub/treesitter_parser.py", source_root / "local_ai_hub" / "treesitter_parser.py"),
        )
    )

    assert identity["benchmark_inputs_sha256"] == hashlib.sha256(framed).hexdigest()
    assert identity["source_root"] == str(source_root.resolve())
    tree = hashlib.sha256(b"T10-PACKAGE-SOURCE-TREE-V1\0")
    for relative in sorted(("code_index.py", "repo_tools.py", "retrieval.py", "treesitter_parser.py")):
        tree.update(f"src/local_ai_hub/{relative}".encode("utf-8") + b"\0")
        tree.update((source_root / "local_ai_hub" / relative).read_bytes())
        tree.update(b"\0")
    assert identity["package_source_tree_sha256"] == tree.hexdigest()


