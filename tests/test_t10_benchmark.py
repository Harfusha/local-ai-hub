def test_concurrent_measurement_reports_overlap_latency_and_coverage() -> None:
    benchmark = _load_benchmark_module()
    lock = threading.Lock()
    active = 0
    peak_active = 0
    call_number = 0

    def operation() -> dict:
        nonlocal active, peak_active, call_number
        with lock:
            active += 1
            peak_active = max(peak_active, active)
            call_number += 1
            current_call = call_number
        time.sleep(0.005)
        with lock:
            active -= 1
        return {
            "success": current_call % 4 != 0,
            "truncated": True,
            "coverage": {"complete": False, "dependent_candidate_count_exact": True},
        }

    measurement = benchmark._measure_concurrent_workload(operation, workers=4, sample_count=8)

    assert peak_active > 1
    assert measurement["latency"]["samples"] == 8
    assert measurement["latency"]["p99_ms"] is not None
    assert measurement["wall_ms"] > 0
    assert measurement["throughput_per_second"] > 0
    assert measurement["outcomes"] == {
        "successful": 6,
        "failed": 2,
        "coverage_reported": 8,
        "coverage_complete": 0,
        "truncated": 8,
        "candidate_count_exact": 8,
    }


