@pytest.mark.skipif(shutil.which("git") is None, reason="git is needed to inspect staged candidate changes")
def test_candidate_patch_fingerprint_includes_staged_changes(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    benchmark = _load_benchmark_module()
    project_root = tmp_path / "repo"
    source_root = project_root / "src"
    tool_path = project_root / "tools" / "benchmark_t10_repository.py"
    benchmark_test_path = project_root / "tests" / "test_t10_benchmark.py"
    consumer_test_path = project_root / "tests" / "test_t10_project_config_consumers.py"
    code_index = source_root / "local_ai_hub" / "code_index.py"
    repo_tools = source_root / "local_ai_hub" / "repo_tools.py"
    treesitter_parser = source_root / "local_ai_hub" / "treesitter_parser.py"
    tool_path.parent.mkdir(parents=True)
    code_index.parent.mkdir(parents=True)
    benchmark_test_path.parent.mkdir(parents=True)
    tool_path.write_bytes(BENCHMARK_PATH.read_bytes())
    benchmark_test_path.write_text("base benchmark tests\n", encoding="utf-8")
    consumer_test_path.write_text("base consumer tests\n", encoding="utf-8")
    code_index.write_text("base index\n", encoding="utf-8")
    repo_tools.write_text("base repo tools\n", encoding="utf-8")
    retrieval = source_root / "local_ai_hub" / "retrieval.py"
    retrieval.write_text("base retrieval ranker\n", encoding="utf-8")
    treesitter_parser.write_text("base parser\n", encoding="utf-8")
    subprocess.run(["git", "-C", str(project_root), "init", "--quiet"], check=True)
    subprocess.run(["git", "-C", str(project_root), "add", "--", "tools", "src"], check=True)
    subprocess.run(
        ["git", "-C", str(project_root), "-c", "user.name=T10", "-c", "user.email=t10@example.invalid", "commit", "--quiet", "-m", "base"],
        check=True,
    )
    monkeypatch.setattr(benchmark, "__file__", str(tool_path))
    monkeypatch.setattr(benchmark, "SOURCE_ROOT", source_root)
    monkeypatch.delenv("T10_BENCH_SOURCE_REVISION", raising=False)
    monkeypatch.delenv("T10_BENCH_SOURCE_FINGERPRINT", raising=False)
    before = benchmark._source_identity()

    code_index.write_text("base index\nstaged candidate change\n", encoding="utf-8")
    subprocess.run(["git", "-C", str(project_root), "add", "--", "src/local_ai_hub/code_index.py"], check=True)
    after = benchmark._source_identity()
    benchmark_test_path.write_text("changed benchmark tests\n", encoding="utf-8")
    after_test = benchmark._source_identity()
    consumer_test_path.write_text("changed consumer tests\n", encoding="utf-8")
    after_consumer_test = benchmark._source_identity()

    assert after["candidate_scoped_patch_sha256"] != before["candidate_scoped_patch_sha256"]
    assert after_test["candidate_scoped_patch_sha256"] != after["candidate_scoped_patch_sha256"]
    assert after_consumer_test["candidate_scoped_patch_sha256"] != after_test["candidate_scoped_patch_sha256"]
    assert after_consumer_test["candidate_scoped_patch_sha256"] != after_test["candidate_scoped_patch_sha256"]


